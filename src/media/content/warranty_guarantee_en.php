	<h1>Warranty and Guarantee under German Law</h1>

	<p>In Germany, the terms warranty and guarantee are often used synonymously in everyday language, but from a legal perspective they describe two completely different concepts.</p>

	<p>Here is an overview that brings clarity to the legal confusion.</p>
</header>

<section>
<h2>1. Statutory Warranty (Liability for Defects)</h2>

<p>Statutory warranty is a legal right. It governs the seller's liability for defects that already existed at the time of purchase (handover of the goods).</p>

<ul>
	<li><strong>Duration:</strong> For new goods, legally 24 months; for used goods, it can be reduced to 12 months.</li>
	<li><strong>Responsible party:</strong> Always the seller (retailer), not the manufacturer.</li>
	<li><strong>Scope:</strong> The buyer primarily has a right to subsequent performance (repair or replacement delivery). If this fails, withdrawal, price reduction, or damages may be claimed.</li>
</ul>
<br>

<h3>Reversal of the Burden of Proof</h3>

<p>This is the key practical point:</p>

<ul>
	<li>During the first 12 months, it is presumed that the defect already existed at the time of purchase. The seller would have to prove otherwise.</li>
	<li>After 12 months, the burden of proof shifts: the buyer must then prove that the defect was already inherent at handover.</li>
</ul>

<blockquote>
<p>Legal basis:</p>

<ul>
	<li>Section 437 BGB: Buyer's rights in the event of defects.</li>
	<li>Section 438 BGB: Limitation period for defect claims.</li>
	<li>Section 477 BGB: Reversal of the burden of proof (especially important for consumer sales).</li>
</ul>
</blockquote>
</section>

<section>
<h2>2. Guarantee</h2>

<p>A guarantee is a voluntary service. It is an additional promise that goes beyond legal obligations.</p>

<ul>
	<li><strong>Duration:</strong> Freely determined by the guarantor (e.g. 6 months, 5 years, or "lifetime").</li>
	<li><strong>Responsible party:</strong> Usually the manufacturer (manufacturer's guarantee), less often the retailer (retailer's guarantee).</li>
	<li><strong>Scope:</strong> The guarantor defines the terms. It often relates to the functionality of certain parts over a specific period.</li>
	<li><strong>Relationship:</strong> A guarantee must never restrict or replace statutory warranty. It exists in parallel.</li>
</ul>

<blockquote>
<p>Legal basis:</p>

<ul>
	<li>Section 443 BGB: Guarantee.</li>
	<li>Section 479 BGB: Special provisions for guarantees in consumer sales (transparency obligations).</li>
</ul>
</blockquote>
</section>

