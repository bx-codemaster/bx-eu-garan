</ul>
</blockquote>
</section>

<section>
<h2>2. Die Garantie</h2>

<p>Die Garantie ist eine freiwillige Leistung. Sie ist ein zusätzliches Versprechen, das über die gesetzlichen Verpflichtungen hinausgeht.</p>

<ul>
	<li><strong>Dauer:</strong> Frei wählbar durch den Garantiegeber (z. B. 6 Monate, 5 Jahre oder "lebenslang").</li>
	<li><strong>Verantwortlich:</strong> Meistens der Hersteller (Herstellergarantie), seltener der Händler (Händlergarantie).</li>
	<li><strong>Inhalt:</strong> Die Bedingungen bestimmt der Garantiegeber selbst. Oft bezieht sie sich auf die Funktionsfähigkeit bestimmter Teile über einen gewissen Zeitraum.</li>
	<li><strong>Verhältnis:</strong> Eine Garantie darf die gesetzliche Gewährleistung niemals einschränken oder ersetzen. Sie besteht parallel dazu.</li>
</ul>

<blockquote>
<p>Rechtsgrundlagen:</p>

<ul>
	<li><a href="https://www.gesetze-im-internet.de/bgb/__443.html" name="$443 BGB" target="_blank">§ 443 BGB: Garantie.</a></li>
	<li><a href="https://www.gesetze-im-internet.de/bgb/__479.html" name="$479 BGB" target="_top">§ 479 BGB: Besondere Bestimmungen für Garantien beim Verbrauchsgüterkauf (Transparenzpflichten).</a></li>
</ul>
</blockquote>
</section>

