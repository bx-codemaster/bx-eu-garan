<h1>Gewährleistung und Garantie im deutschen Recht</h1>

<p>In Deutschland werden die Begriffe Gewährleistung und Garantie im Alltag oft synonym verwendet, rechtlich gesehen beschreiben sie jedoch zwei völlig unterschiedliche Konzepte.</p>

<p>Hier ist eine Übersicht, die Ordnung in das juristische Chaos bringt.</p>
</header>

<section>
<h2>1. Die Gewährleistung (Mängelhaftung)</h2>

<p>Die Gewährleistung ist ein gesetzliches Recht. Sie regelt die Haftung des Verkäufers für Mängel, die bereits zum Zeitpunkt des Kaufs (Übergabe der Ware) bestanden haben.</p>

<ul>
	<li><strong>Dauer:</strong> Bei Neuwaren gesetzlich 24 Monate, bei Gebrauchtwaren kann sie auf 12 Monate verkürzt werden.</li>
	<li><strong>Verantwortlich:</strong> Immer der Verkäufer (Händler), nicht der Hersteller.</li>
	<li><strong>Inhalt:</strong> Der Käufer hat primär Anspruch auf Nacherfüllung (Reparatur oder Ersatzlieferung). Schlägt dies fehl, kommen Rücktritt, Minderung oder Schadensersatz infrage.</li>
</ul>
&nbsp;

<h3>Die Beweislastumkehr</h3>

<p>Dies ist der entscheidende Punkt in der Praxis:</p>

<ul>
	<li>In den ersten 12 Monaten wird vermutet, dass der Mangel schon beim Kauf vorlag. Der Verkäufer müsste das Gegenteil beweisen.</li>
	<li>Nach 12 Monaten tritt die Beweislastumkehr ein: Nun muss der Käufer beweisen, dass der Fehler bereits bei Übergabe im Keim angelegt war.</li>
</ul>

<blockquote>
<p>Rechtsgrundlagen:</p>

<ul>
	<li><a href="https://www.gesetze-im-internet.de/bgb/__437.html" name="$437 BGB" target="_blank">§ 437 BGB: Rechte des Käufers bei Mängeln.</a></li>
